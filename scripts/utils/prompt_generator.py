def generate_text_by_length(target_length: int) -> str:
    """
    生成指定字符长度的测试文本。
    采用循环重复基础语料直到达到目标长度，然后精确截断。
    保证返回的字符串长度 == target_length（当 target_length > 0 时）。
    """
    if target_length <= 0:
        return ""
    
    base_len = len(_BASE_CORPUS)
    # 计算需要重复的次数（+2 确保够长）
    repeat_times = (target_length // base_len) + 2
    full_text = (_BASE_CORPUS * repeat_times)[:target_length]
    
    # 校验长度（调试用）
    if len(full_text) != target_length:
        # 极端情况：如果截断后长度不对（极少发生），手动补齐空格
        if len(full_text) < target_length:
            full_text += " " * (target_length - len(full_text))
        else:
            full_text = full_text[:target_length]
    
    return full_text


